export type UsStateCode = (typeof US_STATES)[number][0];

const NAMES = new Map<string, string>(US_STATES);

/** Public eligibility rule: not available in CA or NY. */
export const UNSERVED_STATES: readonly UsStateCode[] = ['CA', 'NY'];

export const isUsStateCode = (value: string): value is UsStateCode => NAMES.has(value);

export const usStateName = (code: UsStateCode): string => NAMES.get(code) ?? code;

export const isStateServed = (code: UsStateCode): boolean => !UNSERVED_STATES.includes(code);
